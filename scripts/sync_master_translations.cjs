// Apply translations across all locales
languages.forEach(lng => {
  const filePath = path.join(localesDir, lng, 'translation.json');
  if (!fs.existsSync(filePath)) return;

  const currentData = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  let updatedCount = 0;

  for (const [key, langMap] of Object.entries(translationsMatrix)) {
    const val = langMap[lng] || langMap['en'];
    if (val) {
      currentData[key] = val;
      updatedCount++;
    }
  }

  fs.writeFileSync(filePath, JSON.stringify(currentData, null, 2), 'utf8');
  console.log(`Updated ${updatedCount} keys for language: ${lng}`);
});

console.log('Master translation sync finished successfully!');
